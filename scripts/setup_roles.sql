-- Setup Role-Based Access Control (RBAC) for DataMind
-- Feature #8 from DataMind Advanced Features Implementation Guide

USE ROLE ACCOUNTADMIN;

-- 1. Full Analyst Role (can query all tables in TPCH and DATAMIND_DB)
CREATE ROLE IF NOT EXISTS DATAMIND_ANALYST;
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_ANALYST;
GRANT USAGE ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DATAMIND_ANALYST;
GRANT USAGE ON SCHEMA SNOWFLAKE_SAMPLE_DATA.TPCH_SF1 TO ROLE DATAMIND_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA SNOWFLAKE_SAMPLE_DATA.TPCH_SF1 TO ROLE DATAMIND_ANALYST;
GRANT USAGE ON DATABASE DATAMIND_DB TO ROLE DATAMIND_ANALYST;
GRANT USAGE ON SCHEMA DATAMIND_DB.PUBLIC TO ROLE DATAMIND_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND_DB.PUBLIC TO ROLE DATAMIND_ANALYST;

-- 2. Restricted Viewer Role (restricted to non-sensitive tables only)
CREATE ROLE IF NOT EXISTS DATAMIND_VIEWER;
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_VIEWER;
GRANT USAGE ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DATAMIND_VIEWER;
GRANT USAGE ON SCHEMA SNOWFLAKE_SAMPLE_DATA.TPCH_SF1 TO ROLE DATAMIND_VIEWER;
GRANT SELECT ON TABLE SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION TO ROLE DATAMIND_VIEWER;
GRANT SELECT ON TABLE SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION TO ROLE DATAMIND_VIEWER;

-- Grant roles to app user
GRANT ROLE DATAMIND_ANALYST TO USER mwkhan28;
GRANT ROLE DATAMIND_VIEWER TO USER mwkhan28;
